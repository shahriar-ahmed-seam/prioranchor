"""Core domain models, configuration schemas, and typed data contracts for PriorAnchor."""

from __future__ import annotations

import time
from enum import Enum
from typing import List, Optional

from pydantic import BaseModel, Field, field_validator, model_validator


class SchedulerType(str, Enum):
    """Diffusion noise schedulers."""
    DDPM = "ddpm"
    DDIM = "ddim"
    EULER_A = "euler_ancestral"
    FLOW_MATCHING = "flow_matching"


class LossWeightingSchedule(str, Enum):
    """Timestep loss weighting schedules."""
    CONSTANT = "constant"
    MIN_SNR_GAMMA = "min_snr_gamma"
    COSINE = "cosine"
    LINEAR_RAMP = "linear_ramp"


class AdapterType(str, Enum):
    """Parameter-efficient adapter strategies."""
    LORA = "lora"
    DORA = "dora"
    TEXTUAL_INVERSION = "textual_inversion"
    FULL_FINETUNE = "full_finetune"


class TokenIdentifier(BaseModel):
    """Configuration for the rare subject token identifier and vocabulary binding."""
    placeholder_token: str = Field(
        default="[V]",
        description="Rare token placeholder representing the customized subject, e.g. [V] or <sks>."
    )
    class_noun: str = Field(
        ...,
        description="Base semantic class noun, e.g. 'dog', 'sunglasses', 'sneakers'."
    )
    initializer_token: Optional[str] = Field(
        default=None,
        description="Token used to initialize placeholder token embeddings in the text encoder."
    )
    token_id: Optional[int] = Field(
        default=None,
        description="Assigned vocabulary index in the tokenizer."
    )
    rare_token_variance: float = Field(
        default=0.01,
        ge=0.0,
        description="Initial Gaussian noise perturbation variance if embedding is random."
    )

    @field_validator("placeholder_token")
    @classmethod
    def validate_placeholder(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Placeholder token cannot be empty.")
        return v.strip()

    @field_validator("class_noun")
    @classmethod
    def validate_class_noun(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Class noun cannot be empty.")
        return v.strip().lower()


class SubjectDatasetConfig(BaseModel):
    """Configuration for subject instance images and pairing prompts."""
    instance_data_dir: str = Field(
        ...,
        description="Filesystem directory containing 3-10 reference images of the subject."
    )
    instance_prompt: str = Field(
        ...,
        description="Conditioning prompt describing the instance (e.g. 'photo of [V] dog')."
    )
    class_prompt: str = Field(
        ...,
        description="Generic class prompt used for prior preservation, e.g. 'a photo of a dog'."
    )
    resolution: int = Field(
        default=512,
        ge=64,
        description="Image resolution for training inputs."
    )
    center_crop: bool = Field(
        default=False,
        description="Whether to apply center crop or random crop during data augmentation."
    )
    hflip_prob: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0,
        description="Horizontal flip probability (0.0 for asymmetrical subjects)."
    )


class PriorDatasetConfig(BaseModel):
    """Configuration for synthetic prior generation and content-addressable cache."""
    num_class_images: int = Field(
        default=200,
        ge=10,
        description="Number of class images generated by base model for prior preservation."
    )
    class_prompt_templates: List[str] = Field(
        default_factory=lambda: [
            "a photo of a {class_noun}",
            "a rendering of a {class_noun}",
            "a high quality photo of the {class_noun}",
            "a close-up portrait of a {class_noun}",
            "a crisp image of a {class_noun} in natural setting"
        ],
        description="Prompt templates populated with class_noun to generate diverse class priors."
    )
    cache_dir: str = Field(
        default="prior_cache",
        description="Directory storing cached class images indexed by base model hash."
    )
    guidance_scale: float = Field(
        default=7.5,
        gt=0.0,
        description="Classifier-free guidance scale for prior generation."
    )
    num_inference_steps: int = Field(
        default=50,
        ge=10,
        description="Denoising steps for generating class priors."
    )
    seed: int = Field(
        default=42,
        description="Deterministic random seed for class prior generation."
    )


class LoRAConfig(BaseModel):
    """Low-Rank Adaptation hyperparameters."""
    adapter_type: AdapterType = Field(
        default=AdapterType.LORA,
        description="PEFT strategy: lora, dora, textual_inversion, or full_finetune."
    )
    rank: int = Field(
        default=16,
        ge=1,
        le=256,
        description="Rank dimension r of the adaptation matrices."
    )
    alpha: float = Field(
        default=32.0,
        gt=0.0,
        description="LoRA scaling factor alpha; effective scale is alpha / rank."
    )
    dropout: float = Field(
        default=0.05,
        ge=0.0,
        le=0.5,
        description="Dropout rate applied to LoRA intermediate activations."
    )
    target_modules: List[str] = Field(
        default_factory=lambda: ["to_q", "to_k", "to_v", "to_out.0"],
        description="Attention projection modules intercepted by LoRA layers."
    )
    train_text_encoder: bool = Field(
        default=False,
        description="Whether to fine-tune the text encoder alongside the diffusion backbone."
    )
    text_encoder_lr: float = Field(
        default=5e-6,
        gt=0.0,
        description="Learning rate for text encoder projections if enabled."
    )

    @property
    def scaling(self) -> float:
        """Effective multiplicative scaling factor applied to low-rank delta."""
        return self.alpha / float(self.rank)


class OptimizationConfig(BaseModel):
    """Training optimizer, loss weighting, and gradient step configuration."""
    learning_rate: float = Field(
        default=1e-4,
        gt=0.0,
        description="Optimizer base learning rate."
    )
    prior_preservation_lambda: float = Field(
        default=1.0,
        ge=0.0,
        description="Prior-preservation loss coefficient lambda in L_total = L_subj + lambda * L_p."
    )
    loss_schedule: LossWeightingSchedule = Field(
        default=LossWeightingSchedule.CONSTANT,
        description="Loss weighting schedule across training timesteps."
    )
    min_snr_gamma: float = Field(
        default=5.0,
        gt=0.0,
        description="Gamma truncation parameter for Min-SNR weighting."
    )
    lambda_warmup_steps: int = Field(
        default=50,
        ge=0,
        description="Timestep warmup steps for prior loss weighting."
    )
    max_train_steps: int = Field(
        default=800,
        ge=10,
        description="Maximum optimization iterations."
    )
    train_batch_size: int = Field(
        default=1,
        ge=1,
        description="Batch size for subject samples per optimizer step."
    )
    gradient_accumulation_steps: int = Field(
        default=1,
        ge=1,
        description="Accumulation steps before gradient descent update."
    )
    max_grad_norm: float = Field(
        default=1.0,
        gt=0.0,
        description="Gradient norm clipping ceiling."
    )
    adam_beta1: float = Field(default=0.9, ge=0.0, lt=1.0)
    adam_beta2: float = Field(default=0.999, ge=0.0, lt=1.0)
    adam_weight_decay: float = Field(default=1e-2, ge=0.0)
    adam_epsilon: float = Field(default=1e-8, gt=0.0)
    seed: int = Field(default=42)


class TelemetryEvent(BaseModel):
    """Live telemetry event emitted during training iterations."""
    step: int
    subject_loss: float
    prior_loss: float
    total_loss: float
    learning_rate: float
    grad_norm: float
    lambda_weight: float
    timestamp: float = Field(default_factory=time.time)


class PriorAnchorConfig(BaseModel):
    """Root configuration contract for a PriorAnchor training run."""
    base_model_path: str = Field(
        ...,
        description="Path or ID to frozen base model (e.g. runwayml/stable-diffusion-v1-5)."
    )
    token_identifier: TokenIdentifier
    subject_dataset: SubjectDatasetConfig
    prior_dataset: PriorDatasetConfig = Field(default_factory=PriorDatasetConfig)
    lora: LoRAConfig = Field(default_factory=LoRAConfig)
    optimization: OptimizationConfig = Field(default_factory=OptimizationConfig)
    output_dir: str = Field(
        default="checkpoints",
        description="Directory destination for serialized adapters and logs."
    )

    @model_validator(mode="after")
    def validate_instance_prompt_contains_token(self) -> PriorAnchorConfig:
        token = self.token_identifier.placeholder_token
        prompt = self.subject_dataset.instance_prompt
        if token not in prompt:
            raise ValueError(
                f"Subject instance prompt '{prompt}' must contain placeholder token '{token}'."
            )
        return self
